#!/usr/bin/env node
/**
 * 把 `dsh/` 里的 preset 源文件渲染成可安装形态。
 *
 * 要做两件事：
 *  1. `agent.cordis.yml` 里的 `@SPV_PLUGIN@` / `@SPV_CRON_PLUGIN@` 占位符换成
 *     `file://<安装目录>/spv-tools.js` 与 `file://<安装目录>/spv-cron-plugin.js`。
 *     为什么是 file URL 而不是包名：preset 的声明来自 dsh profile 的 patch 层，那一层的模块解析基址是
 *     profile 目录，`wheelchair-agent` 不在 dsh 的安装树里，bare specifier 会 MODULE_NOT_FOUND，整个
 *     preset mount 失败（错误只表现为 "never started"）。file URL 不依赖任何解析表。
 *  2. 生成 `preset-default.patch.yml`：dsh-tui 0.19 的 preset 由 registry 声明，`~/.dsh/.agent-presets/<id>/`
 *     只是元数据目录，不会被自动发现；新会话要用某个 preset，必须有一条声明它的 patch，由 `--patch` 传入。
 *
 * 用法：node scripts/render-preset.mjs <dshDir> <pluginUrl> <cronPluginUrl> <outDir>
 * 退出码：0 成功，2 用法错误，1 源文件缺失/无法写出。
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

/** preset 的声明行：`preset.yml` 的 name/description/order 与 `agent.cordis.yml` 的 plugins 合成一条。 */
const ORDER_FALLBACK = 50

/** 读 `key: value` 形式的简单元数据文件；缺文件时返回空对象。 */
async function readMeta(file) {
  const text = await readFile(file, 'utf8').catch(() => '')
  const meta = {}
  for (const line of text.split('\n')) {
    const match = /^([a-zA-Z]+):\s*(.*)$/.exec(line)
    if (match === null) continue
    meta[match[1]] = match[2].trim()
  }
  return meta
}

/** 把一段 entry 列表整体缩进，供 `plugins:` 之下使用。 */
function indent(text, spaces) {
  const pad = ' '.repeat(spaces)
  return text.split('\n').map(line => (line.trim() === '' ? '' : pad + line)).join('\n')
}

/** 生成 patch 文件内容：一条 preset 声明 + 把 registry 的默认 preset 指向它。 */
function buildPatch({ id, name, description, order, plugins }) {
  const lines = [
    '# Generated by scripts/render-preset.mjs from dsh/preset.yml and dsh/agent.cordis.yml. Do not edit.',
    '#',
    '# Why a patch and not only a directory: dsh-tui 0.19 declares presets through the agent-preset registry,',
    '# so a preset is visible only when some mounted patch declares it. Passing this file with --patch adds the',
    '# declaration and points the roster default at it, which is what makes new sessions start on this preset.',
    '- insert:',
    '    - id: preset-spv',
    "      name: '@deepseek-ai/dsh-agent-preset'",
    '      config:',
    `        id: ${id}`,
    `        name: ${JSON.stringify(name)}`,
    `        description: ${JSON.stringify(description)}`,
    `        order: ${order}`,
    '        plugins:',
    indent(plugins.trimEnd(), 10),
    '',
    '# New sessions adopt this preset unless the caller pins another one. A persisted /preset pick in',
    '# ~/.dsh-tui/agent-preset.json outranks a deployment default, so the launcher also exports',
    '# DSH_TUI_PRESET=spv; the launch instruction is the highest-precedence source.',
    '- id: dsh-tui-agent-preset-registry',
    '  config:',
    `    default: ${id}`,
    '',
  ]
  return lines.join('\n')
}

async function main() {
  const [dshDir, pluginUrl, cronPluginUrl, outDir] = process.argv.slice(2)
  if (!dshDir || !pluginUrl || !cronPluginUrl || !outDir) {
    process.stderr.write('usage: node scripts/render-preset.mjs <dshDir> <pluginUrl> <cronPluginUrl> <outDir>\n')
    return 2
  }
  const id = 'spv'
  const meta = await readMeta(join(dshDir, 'preset.yml'))
  const name = meta.name || 'SPV'
  const description = meta.description || 'Entry session that dispatches work to superagent.'
  const order = Number.parseInt(meta.order ?? '', 10)
  const source = await readFile(join(dshDir, 'agent.cordis.yml'), 'utf8')
  const rendered = source
    .replaceAll('@SPV_PLUGIN@', pluginUrl)
    .replaceAll('@SPV_CRON_PLUGIN@', cronPluginUrl)
  await mkdir(outDir, { recursive: true })
  // Node treats a .js file with no nearby package.json as CommonJS first and re-parses it as ESM, which prints a
  // MODULE_TYPELESS_PACKAGE_JSON warning on every boot. One line removes it.
  await writeFile(join(outDir, 'package.json'), `${JSON.stringify({ type: 'module' }, null, 2)}\n`, 'utf8')
  await writeFile(join(outDir, 'agent.cordis.yml'), rendered, 'utf8')
  await writeFile(join(outDir, 'preset.yml'), await readFile(join(dshDir, 'preset.yml'), 'utf8'), 'utf8')
  const patch = buildPatch({
    id,
    name,
    description,
    order: Number.isInteger(order) ? order : ORDER_FALLBACK,
    plugins: rendered,
  })
  await writeFile(join(outDir, 'preset-default.patch.yml'), patch, 'utf8')
  return 0
}

process.exitCode = await main().catch(error => {
  process.stderr.write(`render-preset: ${error instanceof Error ? error.message : String(error)}\n`)
  return 1
})
