/**
 * Host half of the wheelchair-agent panel: the two `/wheelchair-inbox/*` JSON routes plus the
 * `/wheelchair-settings` route, all on the composition's `webServer` and each behind the
 * composition's connection trust fence. The panel page itself is a Client React component
 * (`./client.js`) in the `main` slot; the Host no longer serves HTML.
 *
 * Security has one home, here. Every route asks `ctx.connection.requestRejection(req)` first:
 * its Host/Origin fence defeats DNS rebinding and cross-site calls, and its browser
 * authentication cookie gates every caller. If the service is absent (a composition that mounts
 * this package without a web connection) the guard is skipped rather than crashing the profile.
 *
 * The actual work lives in `./core/inbox.js` and `./shared/settings.js`. These files, the other
 * core siblings and `./shared/{home,queue,hooks,hook-events}.js` are **copies** generated by `install.sh`
 * from this repository's `src/spv/{inbox,dispatch,hook-runner,paths,archive-effect}.js` and
 * `src/shared/{home,queue,settings,hooks,hook-events}.js`. Keeping
 * the panel self-contained means a preset replacement (another worktree's install.sh) cannot
 * break this package's import, while still leaving exactly one implementation to maintain (see
 * `ARCHITECTURE/webui/index.md`). `settings.js` lives in `lib/shared/` rather than `lib/core/` because the
 * copied `lib/core/inbox.js` imports `../shared/settings.js`, exactly like `queue.js`; `lib/core/`
 * is for files copied from `src/spv/`.
 *
 * The host half also owns the refresh loop: `startInboxWatcher()` is the same implementation the CLI's
 * `inbox watch` uses, and `ctx.effect` stops it when the plugin unloads. Its interval is configured by
 * the settings file's `inbox.intervalSeconds`, the plugin config's `intervalSeconds` or
 * `$SPV_INBOX_INTERVAL_SECONDS` (default 60s; 0 pauses), and the loop re-resolves it before every
 * schedule, so the operator can pause or resume it from the Settings section without a restart.
 */
import {
  INBOX_INTERVAL_DEFAULT,
  createInboxHandler,
  defaultProjectsRoot,
  resolveInboxIntervalSeconds,
  resolveInboxRoot,
  startInboxWatcher,
} from './core/inbox.js'
import { startHookRunner } from './core/hook-runner.js'
import { createArchiveSessionEffect } from './core/archive-effect.js'
import { resolveRoot } from './core/paths.js'
import { buildHookPanel } from './shared/hooks.js'
import { SETTINGS_PATH, createSettingsHandler, ensureSettingsFile } from './shared/settings.js'

export const name = 'wheelchair-agent-webui'
export const inject = ['webServer', 'connection']

const ITEMS_PATH = '/wheelchair-inbox/items'
const REVIEW_PATH = '/wheelchair-inbox/review'

/** The composition's connection service (typed locally: its package is browser-side). */
function connectionOf(ctx) {
  return Reflect.get(ctx, 'connection')
}

/** Upper bound for a lazy service lookup: services may mount after this plugin. */
const SERVICE_WAIT_MS = 5000

/**
 * `ctx.workspaceRegistry` when this composition has one. The direct property is tried first (a mounted
 * service), then `ctx.get` — the supported lazy lookup for a service that mounts later. A throwing
 * getter means "absent", not a plugin failure; the same lookup lives in `src/superagent/watch.js`.
 */
function currentWorkspaceRegistry(ctx) {
  try {
    const direct = Reflect.get(ctx, 'workspaceRegistry')
    if (direct !== undefined && direct !== null) return direct
  } catch {
    // fall through to the lazy lookup
  }
  try {
    return ctx.get?.('workspaceRegistry')
  } catch {
    return undefined
  }
}

/** `ctx.jobs` the same way: used only to refuse archiving a session that still owns a running job. */
function currentJobs(ctx) {
  try {
    const direct = Reflect.get(ctx, 'jobs')
    if (direct !== undefined && direct !== null) return direct
  } catch {
    // fall through to the lazy lookup
  }
  try {
    return ctx.get?.('jobs')
  } catch {
    return undefined
  }
}

/**
 * Wait (bounded) for the workspace registry. The hook runner starts at mount while the workspace service
 * may mount later, and a composition without one must not spin: the wait ends after `SERVICE_WAIT_MS` and
 * the effect degrades to a warning. Same bound and lookup as `src/superagent/watch.js`.
 */
async function waitForWorkspaceRegistry(ctx, timeoutMs = SERVICE_WAIT_MS) {
  const found = currentWorkspaceRegistry(ctx)
  if (found !== undefined && found !== null) return found
  const deadline = Date.now() + timeoutMs
  while (Date.now() < deadline) {
    await new Promise(resolve => {
      const timer = setTimeout(resolve, 100)
      timer.unref?.()
    })
    const registry = currentWorkspaceRegistry(ctx)
    if (registry !== undefined && registry !== null) return registry
  }
  return undefined
}

/** Answer an untrusted/unauthenticated request; true when it was rejected. */
function rejected(ctx, req, res) {
  const connection = connectionOf(ctx)
  if (connection === undefined || connection === null || typeof connection.requestRejection !== 'function') {
    return false
  }
  const rejection = connection.requestRejection(req)
  if (rejection === undefined) return false
  res.statusCode = rejection
  res.end()
  return true
}

/**
 * The plugin config's interval as the settings-store fallback map. Only pass the key when the config
 * actually sets it: `undefined` would be treated as a present-but-invalid config value and add a
 * spurious warning to every snapshot.
 */
function settingsConfig(config) {
  const seconds = config?.intervalSeconds
  return seconds === undefined || seconds === null ? {} : { 'inbox.intervalSeconds': seconds }
}

export function apply(ctx, config = {}) {
  // Resolve once at mount so the first run performs the one-shot migration; the handler and the poller
  // then re-resolve per request/tick, so a mount that had to fall back picks up a later migration.
  resolveInboxRoot()
  // First run on an upgraded machine: ship the self-contained settings file (all defaults, marked in
  // `filled`) so the panel never has to explain a missing file. A failure is a warning, not a mount
  // failure; the Settings page still works with fallback values and reports the write problem on save.
  try {
    ensureSettingsFile()
  } catch (error) {
    ctx.logger?.warn?.(`wheelchair-agent-webui: cannot create the settings file (${error?.message ?? error})`)
  }
  const rootOf = () => resolveInboxRoot()
  const handler = createInboxHandler({ rootOf })
  const settingsHandler = createSettingsHandler({
    config: settingsConfig(config),
    // The panel reads one snapshot: the settings store owns the write path and the hook view is a
    // read-only projection of the same snapshot plus records/hooks.jsonl. A broken projection falls
    // back to `hookView: null` so the Settings section still loads.
    decorate: snapshot => {
      try {
        return { ...snapshot, hookView: buildHookPanel({ settings: snapshot, env: process.env }) }
      } catch (error) {
        return {
          ...snapshot,
          hookView: null,
          hookViewError: error instanceof Error ? error.message : String(error),
        }
      }
    },
  })
  const guarded = async (req, res) => {
    if (rejected(ctx, req, res)) return
    await handler(req, res)
  }
  const guardedSettings = async (req, res) => {
    if (rejected(ctx, req, res)) return
    await settingsHandler(req, res)
  }
  ctx.effect(
    () => ctx.webServer.register({ kind: 'exact', path: ITEMS_PATH, handler: guarded }),
    `wheelchair-agent-webui: GET ${ITEMS_PATH}`,
  )
  ctx.effect(
    () => ctx.webServer.register({ kind: 'exact', path: REVIEW_PATH, handler: guarded }),
    `wheelchair-agent-webui: POST ${REVIEW_PATH}`,
  )
  ctx.effect(
    () => ctx.webServer.register({ kind: 'exact', path: SETTINGS_PATH, handler: guardedSettings }),
    `wheelchair-agent-webui: GET/PUT ${SETTINGS_PATH}`,
  )

  // The live interval seam: called before every schedule. A configured value is still validated once
  // (invalid config warns and falls back to 60s rather than failing the panel); the settings file is
  // re-read by resolveInboxIntervalSeconds() on every call, so a save from the Settings section applies
  // without a restart. Warn only once so an invalid config does not log on every tick.
  let warned = false
  const intervalSecondsOf = () => {
    try {
      return resolveInboxIntervalSeconds(config?.intervalSeconds)
    } catch (error) {
      if (!warned) {
        warned = true
        ctx.logger?.warn?.(
          `wheelchair-agent-webui: invalid inbox interval (${error?.message ?? error}); using ${INBOX_INTERVAL_DEFAULT}s`,
        )
      }
      return INBOX_INTERVAL_DEFAULT
    }
  }
  const initialInterval = intervalSecondsOf()
  if (initialInterval > 0) {
    ctx.logger?.info?.(`wheelchair-inbox: refreshing every ${initialInterval}s`)
  } else {
    ctx.logger?.info?.(
      'wheelchair-inbox: automatic refresh disabled (inbox.intervalSeconds=0); a settings change applies without a restart',
    )
  }
  // Registered even at 0: a paused poller runs no `gh` call and re-checks every second, so enabling it
  // again from the Settings section needs no remount either.
  ctx.effect(() => {
    const watcher = startInboxWatcher({
      rootOf,
      projectsRoot: defaultProjectsRoot(),
      intervalSecondsOf,
      unref: true,
      log: message => {
        const line = `wheelchair-inbox: ${message}`
        if (String(message).startsWith('warning:')) ctx.logger?.warn?.(line)
        else ctx.logger?.info?.(line)
      },
    })
    return watcher.stop
  }, 'wheelchair-agent-webui: inbox poller')

  // The hook runner is the **only** reader for hook events in the deployment: the queue events are read
  // here (not in the SPV session, where the injector consumes them) and the prepare/dispatch spool is
  // drained in the same tick. `unref` keeps the plugin's timer from holding a process open; `ctx.effect`
  // stops it with the plugin. `resolveRoot()` is called per tick so a queue created after mount is seen.
  //
  // One log sink for the runner and its builtin effects, so either one's warning lands on `logger.warn`.
  const hookLog = message => {
    const line = `wheelchair-hooks: ${message}`
    if (String(message).startsWith('warning:')) ctx.logger?.warn?.(line)
    else ctx.logger?.info?.(line)
  }
  // Service-side builtin effect: after `ticket.delivered`, archive the worker session (`worker-<ticketId>`).
  // The registry and jobs lookups are lazy with a bounded wait (both may mount later); a composition
  // without them degrades to one warning and simply does not archive. The effect never throws, so a failed
  // archive cannot affect the operator's scripts, and `stopActivity: false` never kills a turn or a job.
  //
  // Only the *first* delivered event may spend the 5s wait: a composition that has no workspace service
  // would otherwise stall the serial hook drain for 5s on every delivery. Later events look the registry up
  // immediately, so one that mounts late is still used.
  let registryWaitSpent = false
  const workspaceRegistryForArchive = () => {
    if (registryWaitSpent) return currentWorkspaceRegistry(ctx)
    registryWaitSpent = true
    return waitForWorkspaceRegistry(ctx)
  }
  const archiveSessionEffect = createArchiveSessionEffect({
    workspaceRegistryOf: workspaceRegistryForArchive,
    jobsOf: () => currentJobs(ctx),
    log: hookLog,
  })
  ctx.effect(() => {
    const runner = startHookRunner({
      queueRootOf: () => resolveRoot(),
      unref: true,
      log: hookLog,
      effects: { 'builtin:archiveSession': archiveSessionEffect },
    })
    return runner.stop
  }, 'wheelchair-agent-webui: hook runner')
}
