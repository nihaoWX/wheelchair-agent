/**
 * Host half of the review inbox: the three `/wheelchair-inbox/*` routes on the composition's
 * `webServer`, each behind the composition's connection trust fence.
 *
 * Security has one home, here. Every route asks `ctx.connection.requestRejection(req)` first:
 * its Host/Origin fence defeats DNS rebinding and cross-site calls, and its browser
 * authentication cookie gates every caller. If the service is absent (a composition that mounts
 * this package without a web connection) the guard is skipped rather than crashing the profile.
 *
 * The actual work lives in `./core/inbox.js`. That file and its three siblings are **copies**
 * generated by `install.sh` from this repository's `src/spv/{inbox,dispatch,paths}.js` and
 * `src/shared/queue.js`. Keeping the panel self-contained means a preset replacement (another
 * worktree's install.sh) cannot break this package's import, while still leaving exactly one
 * implementation to maintain (see `webui/README.md`).
 */
import { createInboxHandler, resolveInboxRoot } from './core/inbox.js'

export const name = 'wheelchair-agent-webui'
export const inject = ['webServer', 'connection']

const PAGE_PATH = '/wheelchair-inbox/page'
const ITEMS_PATH = '/wheelchair-inbox/items'
const REVIEW_PATH = '/wheelchair-inbox/review'

/** The composition's connection service (typed locally: its package is browser-side). */
function connectionOf(ctx) {
  return Reflect.get(ctx, 'connection')
}

/** Answer an untrusted/unauthenticated request; true when it was rejected. */
function rejected(ctx, req, res) {
  const connection = connectionOf(ctx)
  if (connection === undefined || connection === null || typeof connection.requestRejection !== 'function') {
    return false
  }
  const rejection = connection.requestRejection(req)
  if (rejection === undefined) return false
  res.statusCode = rejection
  res.end()
  return true
}

export function apply(ctx) {
  const root = resolveInboxRoot()
  const handler = createInboxHandler({ root })
  const guarded = async (req, res) => {
    if (rejected(ctx, req, res)) return
    await handler(req, res)
  }
  ctx.effect(
    () => ctx.webServer.register({ kind: 'exact', path: PAGE_PATH, handler: guarded }),
    `wheelchair-agent-webui: GET ${PAGE_PATH}`,
  )
  ctx.effect(
    () => ctx.webServer.register({ kind: 'exact', path: ITEMS_PATH, handler: guarded }),
    `wheelchair-agent-webui: GET ${ITEMS_PATH}`,
  )
  ctx.effect(
    () => ctx.webServer.register({ kind: 'exact', path: REVIEW_PATH, handler: guarded }),
    `wheelchair-agent-webui: POST ${REVIEW_PATH}`,
  )
}
